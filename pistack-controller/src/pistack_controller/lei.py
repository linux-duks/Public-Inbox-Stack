"""Lei: import messages from remote public-inbox externals via saved searches.

Port of ``scripts/lei-daemon.sh``. The one-time setup (creating ``lei q``
searches, initializing inboxes and writing ``lei-output.pi.config``) is a Job;
the recurring ``lei up --all`` is a CronJob scheduled by tinySupervisor.
"""

import os
import subprocess

from tinysupervisor import CronJob, Job

from pistack_controller.config import Config


def lei_init(config: Config) -> int:
    base_dir = config.paths.lei
    serving_address = config.lei.serving_address
    output_config = config.lei.output_config
    os.makedirs(base_dir, exist_ok=True)
    env = dict(os.environ)
    env["PI_CONFIG"] = os.environ.get("PI_CONFIG", "/etc/public-inbox/config")

    for maildir in config.lei.maildirs:
        if not maildir.host:
            print(f"[lei] ERROR: No host configured for '{maildir.name}'")
            continue
        if not maildir.query:
            print(f"[lei] ERROR: No query configured for '{maildir.name}', skipping.")
            continue

        parent = os.path.join(base_dir, maildir.name)
        os.makedirs(parent, exist_ok=True)
        output_path = os.path.join(parent, "INBOX")
        query_file = os.path.join(parent, ".lei-query")

        if not os.path.isdir(os.path.join(parent, "git")):
            print(f"[lei] Initializing inbox '{maildir.name}'")
            result = subprocess.run(
                [
                    "public-inbox-init",
                    "-V2",
                    maildir.name,
                    parent,
                    f"http://{serving_address}/{maildir.name}",
                    f"{maildir.name}@{serving_address}",
                ],
                env=env,
                capture_output=True,
                text=True,
            )
            if result.returncode != 0:
                print(f"[lei] Failed to init '{maildir.name}': {result.stderr.strip()}")

        thread_flag = ["-t"] if maildir.threads else []
        existing_query = ""
        if os.path.isfile(query_file):
            with open(query_file) as handle:
                existing_query = handle.read().strip()

        if not os.path.isdir(output_path):
            print(f"[lei] Creating search for '{maildir.name}'")
            subprocess.run(
                [
                    "lei",
                    "q",
                    "-I",
                    maildir.host,
                    *thread_flag,
                    "-o",
                    output_path,
                    "--dedupe=mid",
                    maildir.query,
                ],
                capture_output=True,
                text=True,
            )
            with open(query_file, "w") as handle:
                handle.write(maildir.query)
        elif existing_query != maildir.query:
            print(f"[lei] Query changed, updating search for '{maildir.name}'")
            subprocess.run(
                ["lei", "forget-search", output_path], capture_output=True, text=True
            )
            subprocess.run(
                [
                    "lei",
                    "q",
                    "-I",
                    maildir.host,
                    *thread_flag,
                    "-o",
                    output_path,
                    "--dedupe=mid",
                    "--augment",
                    maildir.query,
                ],
                capture_output=True,
                text=True,
            )
            with open(query_file, "w") as handle:
                handle.write(maildir.query)
        else:
            print(f"[lei] Search for '{maildir.name}' up to date")

    if output_config:
        os.makedirs(os.path.dirname(output_config), exist_ok=True)
        with open(output_config, "w") as handle:
            handle.write(
                "; Auto-generated by pistack-controller\n; DO NOT EDIT MANUALLY\n\n"
            )
            for maildir in config.lei.maildirs:
                inboxdir = os.path.join(base_dir, maildir.name)
                handle.write(f'[publicinbox "{maildir.name}"]\n')
                handle.write(f"\taddress = {maildir.name}@{serving_address}\n")
                handle.write(f"\turl = /{maildir.name}\n")
                handle.write(f"\tinboxdir = {inboxdir}\n")
                handle.write(f"\twatch = maildir:{os.path.join(inboxdir, 'INBOX')}\n")
                handle.write(f"\tobfuscate = {str(maildir.obfuscate).lower()}\n")
                handle.write("\n")
        print(f"[lei] Config written to {output_config}")
    return 0


def lei_init_job(config: Config) -> Job:
    return Job(
        name="lei_init",
        executable=lambda: lei_init(config),
        depends=["init_folders"],
        dependency_mode="completed",
    )


def lei_up_cronjob(config: Config) -> CronJob:
    return CronJob(
        name="lei_up",
        interval=float(config.lei.check_interval) * 60,
        command="lei up --all",
        depends=["lei_init"],
        dependency_mode="completed",
    )

#!/usr/bin/env bash
set -euo pipefail

CONFIG_FILE="${1:-/config/lei.rules.yaml}"

check_deps() {
    local missing=()
    for cmd in yq lei; do
        type -P "$cmd" &>/dev/null || missing+=("$cmd")
    done
    if [[ ${#missing[@]} -gt 0 ]]; then
        echo "[lei-daemon] ERROR: Missing required dependencies: ${missing[*]}" >&2
        exit 1
    fi
}

parse_config() {
    if [[ ! -f "$CONFIG_FILE" ]]; then
        echo "[lei-daemon] ERROR: Config file not found: $CONFIG_FILE" >&2
        exit 1
    fi

    BASE_DIR=$(yq -r '.["base-dir"]' "$CONFIG_FILE")
    if [[ -z "$BASE_DIR" || "$BASE_DIR" == "null" ]]; then
        echo "[lei-daemon] ERROR: base-dir is required in $CONFIG_FILE" >&2
        exit 1
    fi

    CHECK_INTERVAL=$(yq -r '.check_interval' "$CONFIG_FILE")
    if [[ -z "$CHECK_INTERVAL" || "$CHECK_INTERVAL" == "null" ]]; then
        CHECK_INTERVAL=30
    fi
    if ! [[ "$CHECK_INTERVAL" =~ ^[0-9]+$ ]]; then
        echo "[lei-daemon] ERROR: check_interval must be a positive integer, got: $CHECK_INTERVAL" >&2
        exit 1
    fi

    SERVING_ADDRESS=$(yq -r '.serving_address // "localhost"' "$CONFIG_FILE")
    if [[ -z "$SERVING_ADDRESS" || "$SERVING_ADDRESS" == "null" ]]; then
        SERVING_ADDRESS="localhost"
    fi

    OUTPUT_CONFIG=$(yq -r '.["output-config"]' "$CONFIG_FILE")
    if [[ "$OUTPUT_CONFIG" == "null" ]]; then
        OUTPUT_CONFIG=""
    fi

    DEFAULT_HOST=$(yq -r '.default_settings.host' "$CONFIG_FILE")
    if [[ "$DEFAULT_HOST" == "null" ]]; then
        DEFAULT_HOST=""
    fi

    MAILDIR_NAMES=$(yq -r '.maildirs | keys | .[]' "$CONFIG_FILE" 2>/dev/null || true)
    if [[ -z "$MAILDIR_NAMES" ]]; then
        echo "[lei-daemon] WARNING: No maildirs defined in config." >&2
    fi
}

setup_search() {
    local name="$1"
    local host="$2"
    local query="$3"
    local output_path="$BASE_DIR/$name/INBOX"
    local parent_dir="$BASE_DIR/$name"
    local query_file="$parent_dir/.lei-query"

    echo "[lei-daemon] Processing '$name'..."

    mkdir -p "$parent_dir"

    if [[ ! -d "$output_path" ]]; then
        echo "[lei-daemon]   Creating new search: lei q -I $host -o $output_path --dedupe=mid"
        lei q -I "$host" -o "$output_path" --dedupe=mid "$query"
        echo "$query" > "$query_file"
        echo "[lei-daemon]   Search created."
    else
        local existing_query=""
        if [[ -f "$query_file" ]]; then
            existing_query=$(cat "$query_file")
        fi

        if [[ "$existing_query" != "$query" ]]; then
            echo "[lei-daemon]   Query changed, updating search..."
            echo "[lei-daemon]   Old: ${existing_query:-<unknown>}"
            echo "[lei-daemon]   New: $query"
            lei forget-search "$output_path" 2>/dev/null || true
            lei q -I "$host" -o "$output_path" --dedupe=mid --augment "$query"
            echo "$query" > "$query_file"
            echo "[lei-daemon]   Search updated."
        else
            echo "[lei-daemon]   Search exists and query matches, skipping."
        fi
    fi
}

init_inbox() {
    local name="$1"
    local inboxdir="$BASE_DIR/$name"

    if [[ -d "$inboxdir/git" ]]; then
        echo "[lei-daemon]   Inbox '$name' already initialized at $inboxdir"
        return 0
    fi

    echo "[lei-daemon]   Initializing inbox: public-inbox-init -V2 '$name' '$inboxdir' 'http://$SERVING_ADDRESS/$name' '$name@$SERVING_ADDRESS'"
    mkdir -p "$inboxdir"
    public-inbox-init -V2 "$name" "$inboxdir" "http://$SERVING_ADDRESS/$name" "$name@$SERVING_ADDRESS"
    echo "[lei-daemon]   Inbox initialized."
}

generate_config() {
    if [[ -z "$OUTPUT_CONFIG" ]]; then
        echo "[lei-daemon] No output-config specified, skipping config generation."
        return
    fi

    echo "[lei-daemon] Generating $OUTPUT_CONFIG..."

    local config_dir
    config_dir=$(dirname "$OUTPUT_CONFIG")
    mkdir -p "$config_dir"

    {
        echo "; Auto-generated by lei-daemon.sh"
        echo "; DO NOT EDIT MANUALLY"
        echo ""

        while IFS= read -r name; do
            [[ -z "$name" ]] && continue
            local inboxdir="$BASE_DIR/$name"
            local watch_path="$BASE_DIR/$name/INBOX"

            printf '[publicinbox "%s"]\n' "$name"
            printf '\taddress = %s@%s\n' "$name" "$SERVING_ADDRESS"
            printf '\turl = /%s\n' "$name"
            printf '\tinboxdir = %s\n' "$inboxdir"
            printf '\twatch = maildir:%s\n' "$watch_path"
            echo ""
        done <<<"$MAILDIR_NAMES"
    } > "$OUTPUT_CONFIG"

    echo "[lei-daemon] Config written to $OUTPUT_CONFIG"
}

startup() {
    local host query

    while IFS= read -r name; do
        [[ -z "$name" ]] && continue

        host=$(yq -r ".maildirs[\"$name\"].host" "$CONFIG_FILE")
        if [[ -z "$host" || "$host" == "null" ]]; then
            host="$DEFAULT_HOST"
        fi
        if [[ -z "$host" ]]; then
            echo "[lei-daemon] ERROR: No host configured for '$name' and no default_settings.host" >&2
            continue
        fi

        query=$(yq -r ".maildirs[\"$name\"].query" "$CONFIG_FILE")
        if [[ -z "$query" || "$query" == "null" ]]; then
            echo "[lei-daemon] ERROR: No query configured for '$name', skipping." >&2
            continue
        fi

        init_inbox "$name"
        setup_search "$name" "$host" "$query"
    done <<<"$MAILDIR_NAMES"

    generate_config
}

cleanup() {
    echo "[lei-daemon] Shutting down..."
    exit 0
}

main() {
    check_deps
    parse_config

    echo "[lei-daemon] Starting up with config: $CONFIG_FILE"
    echo "[lei-daemon] Base dir: $BASE_DIR"
    echo "[lei-daemon] Check interval: ${CHECK_INTERVAL}min"

    startup

    echo "[lei-daemon] Entering update loop (lei up --all every ${CHECK_INTERVAL}min)..."
    trap cleanup SIGTERM SIGINT

    while true; do
        echo "[lei-daemon] Running lei up --all..."
        lei up --all || echo "[lei-daemon] lei up failed, will retry next cycle." >&2
        sleep $((CHECK_INTERVAL * 60))
    done
}

main
